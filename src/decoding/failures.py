"""Typed failures and immutable usage records for constrained generation."""

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

FailureReason = Literal[
    "token_limit",
    "byte_limit",
    "no_continuation",
    "context_limit",
    "invalid_logits",
    "nonfinite_number",
    "invalid_value",
]
"""Reasons a generation attempt can fail."""


class GenerationUsage(BaseModel):
    """Immutable counters and configured limits for one generation attempt.

    Attributes:
        generated_tokens: Number of tokens generated so far.
        generated_bytes: Number of output bytes generated so far.
        context_tokens: Number of tokens in the active context.
        logits_calls: Number of logits queries made.
        max_new_tokens: Maximum generated token count for this attempt.
        max_value_bytes: Maximum generated byte count for this attempt.
        max_context_tokens: Maximum context token count for this attempt.
    """

    model_config = ConfigDict(frozen=True, strict=True, extra="forbid")

    generated_tokens: int = Field(default=0, ge=0)
    generated_bytes: int = Field(default=0, ge=0)
    context_tokens: int = Field(default=0, ge=0)
    logits_calls: int = Field(default=0, ge=0)
    max_new_tokens: int = Field(ge=1)
    max_value_bytes: int = Field(ge=1)
    max_context_tokens: int = Field(ge=1)


class DecodeFailure(ValueError):
    """A typed, user-readable failure raised during constrained decoding.

    Args:
        reason: Stable machine-readable reason for the failure.
        message: Human-readable explanation.
        usage: Immutable usage counters and limits at the point of failure.
    """

    def __init__(
        self, reason: FailureReason, message: str, usage: GenerationUsage
    ) -> None:
        super().__init__(message)
        self.reason = reason
        self.usage = usage


class FailureRecord(BaseModel):
    """Immutable structured record describing a failed generation attempt.

    Attributes:
        prompt_index: Optional index of the prompt that failed.
        phase: Whether failure occurred during selection or parameter decoding.
        argument_path: Path to the argument associated with the failure.
        attempt: One-based number, limited to the initial try and one retry.
        reason: Stable machine-readable reason for the failure.
        message: Human-readable explanation.
        usage: Immutable usage counters and limits at the point of failure.
        retry_scheduled: Whether a retry was scheduled for this failure.
    """

    model_config = ConfigDict(frozen=True, strict=True, extra="forbid")

    prompt_index: int | None = Field(default=None, ge=0)
    phase: Literal["selection", "parameter"]
    argument_path: tuple[str | int, ...] = ()
    attempt: int = Field(ge=1, le=2)
    reason: FailureReason
    message: str
    usage: GenerationUsage
    retry_scheduled: bool = False


RECOVERABLE_REASONS: frozenset[FailureReason] = frozenset(
    {"token_limit", "no_continuation", "nonfinite_number", "invalid_value"}
)
"""Failure reasons that may qualify for a retry."""


def can_retry(error: BaseException) -> bool:
    """Return whether a typed decode failure has a recoverable reason.

    Args:
        error: Exception raised by the generation attempt.

    Returns:
        ``True`` only for a :class:`DecodeFailure` whose reason is in
        :data:`RECOVERABLE_REASONS`.
    """
    return (
        isinstance(error, DecodeFailure)
        and error.reason in RECOVERABLE_REASONS
    )
